from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import pandas as pd

import run_expanded_scale_lean_benchmark as lean


ROOT = Path(__file__).resolve().parent


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run the lean blocked benchmark for one expanded dataset.")
    parser.add_argument("--dataset-id", required=True)
    parser.add_argument("--prefix", default="")
    parser.add_argument("--registry", type=Path, default=ROOT / "EXPANDED_SCALE_DATASETS.csv")
    return parser.parse_args()


def safe_prefix(dataset_id: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "_", dataset_id).strip("_").upper() + "_LEAN_BENCHMARK"


def selected_config(dataset_id: str, registry: Path) -> lean.base.BenchmarkDataset:
    for config in lean.dataset_configs(registry):
        if config.dataset_id == dataset_id:
            return config
    raise ValueError(f"Dataset not found in expanded registry: {dataset_id}")


def write_report(prefix: str, summary: pd.DataFrame, pairwise: pd.DataFrame, guardrail: pd.DataFrame, fold_reports: list[dict], config: dict) -> None:
    fold_df = pd.DataFrame(fold_reports)
    lines = [
        f"# {config['dataset_id']} Lean Benchmark",
        "",
        "Single-dataset blocked benchmark generated by the GEO-100 expansion pipeline.",
        "",
        "## Fold Size",
        "",
        "| fold | train cells | test cells | train groups | test groups |",
        "|---:|---:|---:|---:|---:|",
    ]
    for row in fold_df.sort_values("fold").itertuples(index=False):
        lines.append(
            f"| {int(row.fold)} | {int(row.train_cells)} | {int(row.test_cells)} | "
            f"{int(row.train_groups)} | {int(row.test_groups)} |"
        )

    lines.extend(["", "## Model Summary", "", "| model | accuracy | macro-F1 | conflict rate |", "|---|---:|---:|---:|"])
    for row in summary.sort_values("model").itertuples(index=False):
        lines.append(f"| {row.model} | {row.accuracy:.4f} | {row.macro_f1:.4f} | {row.conflict_rate:.4f} |")

    lines.extend(
        [
            "",
            "## Specificity Guardrail",
            "",
            "| learned delta macro-F1 | learned pass | context delta macro-F1 | context pass | interpretation |",
            "|---:|---|---:|---|---|",
        ]
    )
    for row in guardrail.itertuples(index=False):
        lines.append(
            f"| {row.learned_specific_macro_f1_delta:+.4f} | "
            f"{'yes' if row.learned_passes_guardrail else 'no'} | "
            f"{row.context_specific_macro_f1_delta:+.4f} | "
            f"{'yes' if row.context_specific_passes_guardrail else 'no'} | {row.interpretation} |"
        )

    lines.extend(["", "## Config", "", "```json", json.dumps(config, indent=2), "```", ""])
    (ROOT / f"{prefix}.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    args = parse_args()
    prefix = args.prefix or safe_prefix(args.dataset_id)
    config = selected_config(args.dataset_id, args.registry)
    output = lean.evaluate_dataset(config)
    calls = output["calls"]
    markers = output["markers"]
    fold_reports = output["fold_reports"]
    summary, per_label, pairwise, guardrail = lean.summarize_all(calls)

    calls.to_csv(ROOT / f"{prefix}_calls.csv.gz", index=False)
    markers.to_csv(ROOT / f"{prefix}_learned_markers.csv", index=False)
    summary.to_csv(ROOT / f"{prefix}_summary.csv", index=False)
    per_label.to_csv(ROOT / f"{prefix}_per_label.csv", index=False)
    pairwise.to_csv(ROOT / f"{prefix}_pairwise.csv", index=False)
    guardrail.to_csv(ROOT / f"{prefix}_guardrail.csv", index=False)
    (ROOT / f"{prefix}_folds.json").write_text(json.dumps(fold_reports, indent=2), encoding="utf-8")
    report = {
        "dataset": output["config"],
        "folds": fold_reports,
        "summary": json.loads(summary.to_json(orient="records")),
        "pairwise": json.loads(pairwise.to_json(orient="records")),
        "guardrail": json.loads(guardrail.to_json(orient="records")),
    }
    (ROOT / f"{prefix}_report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    write_report(prefix, summary, pairwise, guardrail, fold_reports, output["config"])
    print(json.dumps({"dataset_id": args.dataset_id, "prefix": prefix, "n_calls": int(calls.shape[0])}, indent=2))
    print(summary.sort_values("model").to_string(index=False))
    print(guardrail.to_string(index=False))


if __name__ == "__main__":
    main()
