ROOT = Path(__file__).resolve().parent
QUEUE = ROOT / "HUNDRED_DATASET_EXPANSION_QUEUE.csv"
DOWNLOAD_ROOT = ROOT / "GEO_100_QUEUE"
REPORT = ROOT / "HUNDRED_DATASET_DOWNLOAD_REPORT.csv"
MANIFEST = ROOT / "HUNDRED_DATASET_DOWNLOAD_MANIFEST.json"

USER_AGENT = "NicheTypeR hundred-dataset benchmark expansion/0.1"

KEEP_RE = re.compile(
    r"("
    r"\.h5ad(\.gz)?$|\.h5$|\.loom$|"
    r"matrix\.mtx(\.gz)?$|exprmat[_-]?file\.csv(\.gz)?$|cell[_-]?by[_-]?gene\.(csv|tsv|txt)(\.gz)?$|"
    r"digital[_-]?expression\.(csv|tsv|txt)(\.gz)?$|normalized[_-]?matrix\.(csv|tsv|txt)(\.gz)?$|"
    r"counts?([_-]|[^\\/]*)(matrix|metadata)?[^\\/]*\.(csv|tsv|txt)(\.gz)?$|count[_-]?matrix[^\\/]*\.(csv|tsv|txt)(\.gz)?$|"
    r"barcodes\.tsv(\.gz)?$|features\.tsv(\.gz)?$|genes\.tsv(\.gz)?$|"
    r"cells?[-_][^\\/]*\.(csv|tsv|txt)(\.gz)?$|"
    r"cells\.parquet(\.gz)?$|"
    r"metadata|meta[_-]?data|cell[_-]?type|celltype|annotation|(?:^|[_-])anno(?:[_-]|$)|annot|label|cluster|"
    r"coordinate|coordinates|coords|spatial|tissue_positions|positions|region|domain|banksy|leiden|louvain"
    r")",
    re.I,
)

DROP_RE = re.compile(
    r"("
    r"image|hires|lowres|tiff|tif|jpg|jpeg|png|html|pdf|docx?|pptx?|xlsx|xls$|"
    r"svg|xml|loompa|fastq|bam|bai|cram|bigwig|bw|bedgraph|transcripts\.parquet|"
    r"cell_boundaries\.parquet|nucleus_boundaries\.parquet"
    r")",
    re.I,
)
IMMUNE_RECEPTOR_RE = re.compile(
    r"(filtered[_-]?contig|all[_-]?contig|contig[_-]?annotations?|consensus[_-]?annotations?|"
    r"vdj[_-]?[bt]?|bcr|tcr|clonotype|airr)",
    re.I,
)


def skip_non_celltype_annotation(name: str) -> bool:
    return bool(IMMUNE_RECEPTOR_RE.search(name))

ESSENTIAL_RE = re.compile(
    r"("
    r"\.h5ad(\.gz)?$|\.h5$|matrix\.mtx(\.gz)?$|exprmat[_-]?file\.csv(\.gz)?$|"
    r"cell[_-]?by[_-]?gene\.(csv|tsv|txt)(\.gz)?$|digital[_-]?expression\.(csv|tsv|txt)(\.gz)?$|"
    r"normalized[_-]?matrix\.(csv|tsv|txt)(\.gz)?$|counts?([_-]|[^\\/]*)(matrix|metadata)?[^\\/]*\.(csv|tsv|txt)(\.gz)?$|"
    r"count[_-]?matrix[^\\/]*\.(csv|tsv|txt)(\.gz)?$|barcodes\.tsv(\.gz)?$|features\.tsv(\.gz)?$|"
    r"genes\.tsv(\.gz)?$|cells?[-_][^\\/]*\.(csv|tsv|txt)(\.gz)?$|metadata|cell[_-]?type|celltype|annotation|(?:^|[_-])anno(?:[_-]|$)|label|cluster|"
    r"cells\.parquet(\.gz)?$|"
    r"coordinate|coordinates|tissue_positions|spatial_enrichment|region|domain|banksy|leiden|louvain"
    r")",
    re.I,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Fetch GEO files for the NicheTypeR 100-source expansion queue.")
    parser.add_argument("--queue", default=str(QUEUE), help="CSV generated by build_hundred_dataset_expansion_queue.py")
    parser.add_argument("--out", default=str(DOWNLOAD_ROOT), help="Download directory")
    parser.add_argument("--status", action="append", default=None, help="Queue status to include; may be repeated")
    parser.add_argument("--accession", action="append", default=None, help="Specific accession to fetch; may be repeated")
    parser.add_argument("--limit", type=int, default=10, help="Maximum accessions to process")
    parser.add_argument("--file-limit-per-accession", type=int, default=12, help="Maximum selected files per accession")
    parser.add_argument("--max-file-mb", type=float, default=250.0, help="Skip selected files larger than this")
    parser.add_argument("--max-total-mb", type=float, default=1500.0, help="Stop before total downloaded bytes exceed this")
    parser.add_argument("--download", action="store_true", help="Actually download selected files; otherwise fetch filelists only")
    parser.add_argument("--decompress-h5ad", action="store_true", help="Decompress .h5ad.gz files after download")
    parser.add_argument("--sleep", type=float, default=0.5, help="Seconds between accessions")
    parser.add_argument("--report", default=str(REPORT), help="CSV download report path")
    parser.add_argument("--manifest", default=str(MANIFEST), help="JSON manifest path")
    return parser.parse_args()


def session() -> requests.Session:
    urllib3.disable_warnings(urllib3.exceptions.InsecureRequestWarning)
    sess = requests.Session()
    sess.trust_env = False
    sess.headers.update({"User-Agent": USER_AGENT})
    return sess


def series_prefix(accession: str) -> str:
    return accession[:6] + "nnn"


def fallback_filelist_url(accession: str) -> str:
    return f"https://ftp.ncbi.nlm.nih.gov/geo/series/{series_prefix(accession)}/{accession}/suppl/filelist.txt"


def suppl_base_url(accession: str) -> str:
    return f"https://ftp.ncbi.nlm.nih.gov/geo/series/{series_prefix(accession)}/{accession}/suppl"


def gsm_prefix(gsm: str) -> str:
    # GEO sample directories replace the final three numeric digits with
    # ``nnn``.  Slicing at a fixed position fails for eight-digit GSM IDs.
    match = re.fullmatch(r"GSM(\d+)", gsm)
    if match is None or len(match.group(1)) <= 3:
        raise ValueError(f"Invalid GSM accession: {gsm}")
    return f"GSM{match.group(1)[:-3]}nnn"


def sample_base_url(name: str) -> str | None:
    match = re.match(r"^(GSM\d+)_", name)
    if not match:
        return None
    gsm = match.group(1)
    return f"https://ftp.ncbi.nlm.nih.gov/geo/samples/{gsm_prefix(gsm)}/{gsm}/suppl"


def candidate_urls(accession: str, name: str) -> list[str]:
    urls = []
    sample_base = sample_base_url(name)
    if sample_base is not None:
        urls.append(f"{sample_base}/{quote(name)}")
    urls.append(f"{suppl_base_url(accession)}/{quote(name)}")
    return urls


def fetch_text(sess: requests.Session, url: str) -> str:
    response = sess.get(url, timeout=60, verify=False)
    response.raise_for_status()
    return response.text


def parse_filelist(text: str) -> pd.DataFrame:
    df = pd.read_csv(io.StringIO(text), sep="\t", dtype=str).fillna("")
    if "Size" in df.columns:
        df["size_bytes"] = pd.to_numeric(df["Size"], errors="coerce").fillna(0).astype("int64")
    else:
        df["size_bytes"] = 0
    return df


def fetch_size(sess: requests.Session, url: str) -> int:
    try:
        response = sess.head(url, timeout=30, verify=False, allow_redirects=True)
        response.raise_for_status()
        return int(response.headers.get("Content-Length", "0") or 0)
    except Exception:
        return 0


def parse_directory_listing(sess: requests.Session, accession: str) -> pd.DataFrame:
    base_url = suppl_base_url(accession) + "/"
    text = fetch_text(sess, base_url)
    hrefs = re.findall(r'href="([^"#?]+)"', text, flags=re.I)
    rows = []
    for href in hrefs:
        name = unquote(href.strip())
        if not name or name in {"../", ".."} or name.endswith("/"):
            continue
        name = Path(name).name
        if DROP_RE.search(name) and not ESSENTIAL_RE.search(name):
            continue
        if skip_non_celltype_annotation(name):
            continue
        if not KEEP_RE.search(name):
            continue
        url = base_url + quote(name)
        rows.append(
            {
                "#Archive/File": "file",
                "Name": name,
                "Size": "",
                "Type": "",
                "url_override": url,
                "size_bytes": fetch_size(sess, url),
            }
        )
    return pd.DataFrame(rows)


def selection_reason(name: str, file_type: str) -> str:
    text = f"{name} {file_type}"
    if skip_non_celltype_annotation(text):
        return "non_celltype_annotation"
    if re.search(r"\.h5ad(\.gz)?$", name, re.I):
        if re.search(r"(^|[_-])label([_-]|$)|labeled", name, re.I) and not re.search(r"unlabel", name, re.I):
            return "h5ad_label"
        return "h5ad"
    if re.search(r"\.h5$", name, re.I):
        return "h5"
    if re.search(r"matrix\.mtx(\.gz)?$", name, re.I):
        return "matrix_market"
    if re.search(
        r"(exprmat[_-]?file|cell[_-]?by[_-]?gene|digital[_-]?expression|normalized[_-]?matrix|"
        r"count[_-]?matrix|counts?([_-]|[^\\/]*)(matrix|metadata)?)"
        r"\.(csv|tsv|txt)(\.gz)?$",
        name,
        re.I,
    ):
        return "expression_csv"
    if re.search(r"barcodes\.tsv|features\.tsv|genes\.tsv", name, re.I):
        return "matrix_index"
    if re.search(
        r"cells\.parquet|cell_boundaries\.parquet|nucleus_boundaries\.parquet|cells?[-_][^\\/]*\.(csv|tsv|txt)(\.gz)?$",
        name,
        re.I,
    ):
        return "cell_geometry"
    if re.search(r"metadata|cell[_-]?type|celltype|annotation|(?:^|[_-])anno(?:[_-]|$)|label|cluster", text, re.I):
        return "label_or_metadata"
    if re.search(r"coordinate|coordinates|coords|spatial|tissue_positions|positions", text, re.I):
        return "coordinate"
    if re.search(r"region|domain|banksy|leiden|louvain", text, re.I):
        return "domain_or_cluster"
    return "other"


def filtered_counterpart_for_raw_10x_h5(name: str) -> str | None:
    if not re.search(r"raw[_-]feature[_-]bc[_-]matrix\.h5(\.gz)?$", name, re.I):
        return None
    return re.sub(r"raw([_-]feature[_-]bc[_-]matrix\.h5(\.gz)?)$", r"filtered\1", name, flags=re.I)


def select_files(filelist: pd.DataFrame, max_file_mb: float, limit: int) -> pd.DataFrame:
    rows = []
    for _, row in filelist.iterrows():
        name = str(row.get("Name", ""))
        file_type = str(row.get("Type", ""))
        kind = str(row.get("#Archive/File", ""))
        size = int(row.get("size_bytes", 0) or 0)
        if kind.lower() != "file":
            continue
        if DROP_RE.search(name) and not ESSENTIAL_RE.search(name):
            continue
        if skip_non_celltype_annotation(name):
            rows.append({**row.to_dict(), "selected": False, "selection_reason": "non_celltype_annotation"})
            continue
        if not KEEP_RE.search(name):
            continue
        if size > max_file_mb * 1024 * 1024:
            rows.append({**row.to_dict(), "selected": False, "selection_reason": "skip_too_large"})
            continue
        reason = selection_reason(name, file_type)
        rows.append({**row.to_dict(), "selected": True, "selection_reason": reason})

    selected = pd.DataFrame(rows)
    if selected.empty:
        return selected

    available_names = {str(name).lower() for name in filelist.get("Name", pd.Series(dtype=str)).astype(str)}
    skip_raw_mask = []
    for name in selected["Name"].astype(str):
        counterpart = filtered_counterpart_for_raw_10x_h5(name)
        skip_raw_mask.append(counterpart is not None and counterpart.lower() in available_names)
    if any(skip_raw_mask):
        selected.loc[skip_raw_mask, "selected"] = False
        selected.loc[skip_raw_mask, "selection_reason"] = "raw_matrix_skipped_filtered_available"

    reason_rank = {
        "h5ad_label": 0,
        "h5ad": 1,
        "label_or_metadata": 2,
        "domain_or_cluster": 3,
        "coordinate": 4,
        "h5": 5,
        "cell_geometry": 6,
        "expression_csv": 7,
        "matrix_market": 8,
        "matrix_index": 9,
        "other": 7,
        "raw_matrix_skipped_filtered_available": 97,
        "non_celltype_annotation": 98,
        "skip_too_large": 99,
    }
    selected["_rank"] = selected["selection_reason"].map(reason_rank).fillna(50).astype(int)
    selected = selected.sort_values(["selected", "_rank", "size_bytes", "Name"], ascending=[False, True, True, True])
    selected = selected.drop(columns=["_rank"])
    return selected.head(limit).copy()


def benchmark_evidence_reason(selected: pd.DataFrame) -> tuple[bool, str]:
    if selected.empty:
        return False, "no selected files after filename and size filtering"
    usable = selected[selected.get("selected", False).astype(bool)].copy()
    if usable.empty:
        return False, "all potentially relevant files were skipped by caps or filters"
    names = " ".join(usable["Name"].astype(str).tolist())
    reasons = set(usable["selection_reason"].astype(str).tolist())
    has_h5ad = any(re.search(r"\.h5ad(\.gz)?$", name, re.I) for name in usable["Name"].astype(str))
    has_expression = bool(reasons & {"h5", "matrix_market", "expression_csv"})
    has_label = bool(reasons & {"label_or_metadata", "domain_or_cluster"}) or bool(
        re.search(r"metadata|cell[_-]?type|celltype|annotation|annot|label|cluster|domain|region", names, re.I)
    )
    has_coordinate = bool(reasons & {"coordinate", "cell_geometry", "label_or_metadata"}) or bool(
        re.search(r"metadata|coordinate|coordinates|coords|spatial|tissue_positions|positions|cells\.parquet", names, re.I)
    )
    if has_h5ad:
        return True, "h5ad selected; labels/coordinates will be inspected during prepare"
    if has_expression and has_label and has_coordinate:
        return True, "selected files include expression, label/metadata and spatial coordinate evidence"
    missing = []
    if not has_expression:
        missing.append("expression")
    if not has_label:
        missing.append("label/metadata")
    if not has_coordinate:
        missing.append("spatial coordinates")
    return False, "selected files lack " + ", ".join(missing)


def download_one(sess: requests.Session, urls: list[str], dest: Path) -> tuple[str, int, str, str]:
    dest.parent.mkdir(parents=True, exist_ok=True)
    if dest.exists() and dest.stat().st_size > 0:
        return "exists", dest.stat().st_size, "", ""
    tmp = dest.with_suffix(dest.suffix + ".part")
    errors = []
    for url in urls:
        resume_at = tmp.stat().st_size if tmp.exists() else 0
        bytes_written = resume_at
        headers = {"Range": f"bytes={resume_at}-"} if resume_at > 0 else {}
        try:
            with sess.get(url, stream=True, timeout=180, verify=False, headers=headers) as response:
                response.raise_for_status()
                mode = "ab" if resume_at > 0 and response.status_code == 206 else "wb"
                if mode == "wb":
                    bytes_written = 0
                with tmp.open(mode) as handle:
                    for chunk in response.iter_content(chunk_size=1024 * 1024):
                        if not chunk:
                            continue
                        handle.write(chunk)
                        bytes_written += len(chunk)
            tmp.replace(dest)
            return "downloaded", bytes_written, url, ""
        except Exception as exc:
            errors.append(f"{url}: {exc}")
            if tmp.exists():
                tmp.unlink()
    return "download_error", 0, "", " | ".join(errors)


def maybe_decompress_h5ad(path: Path) -> str:
    if not path.name.lower().endswith(".h5ad.gz"):
        return ""
    out = path.with_suffix("")
    if out.exists() and out.stat().st_size > 0:
        return str(out.name)
    tmp = out.with_suffix(out.suffix + ".part")
    with gzip.open(path, "rb") as src, tmp.open("wb") as dst:
        shutil.copyfileobj(src, dst)
    tmp.replace(out)
    return str(out.name)


def main() -> None:
    args = parse_args()
    report_path = Path(args.report)
    manifest_path = Path(args.manifest)
    queue = pd.read_csv(args.queue)
    statuses = args.status or ["download_now_h5ad_priority", "download_now_structured_files", "resume_download_and_parse"]
    subset = queue[queue["benchmark_status"].isin(statuses)].copy()
    if args.accession:
        wanted = set(args.accession)
        subset = queue[queue["accession"].isin(wanted)].copy()
        missing = sorted(wanted - set(subset["accession"].astype(str)))
        if missing:
            subset = pd.concat(
                [
                    subset,
                    pd.DataFrame(
                        [
                            {
                                "accession": acc,
                                "filelist_url": fallback_filelist_url(acc),
                                "benchmark_status": "explicit_accession",
                            }
                            for acc in missing
                        ]
                    ),
                ],
                ignore_index=True,
            )
    subset = subset[subset["accession"].astype(str).str.startswith("GSE")]
    subset = subset.head(args.limit).copy()

    out_root = Path(args.out)
    out_root.mkdir(parents=True, exist_ok=True)
    sess = session()
    records = []
    manifest = {"download_root": str(out_root), "accessions": []}
    total_downloaded = 0

    for row in subset.itertuples(index=False):
        acc = str(row.accession)
        acc_dir = out_root / acc
        acc_dir.mkdir(parents=True, exist_ok=True)
        filelist_url = str(getattr(row, "filelist_url", "") or fallback_filelist_url(acc))
        if not filelist_url.startswith("http"):
            filelist_url = fallback_filelist_url(acc)
        print(f"[{acc}] fetching filelist", flush=True)
        try:
            text = fetch_text(sess, filelist_url)
            (acc_dir / "filelist.txt").write_text(text, encoding="utf-8")
            filelist = parse_filelist(text)
            selected = select_files(filelist, args.max_file_mb, args.file_limit_per_accession)
            selected.to_csv(acc_dir / "selected_files.csv", index=False)
        except Exception as exc:
            try:
                filelist = parse_directory_listing(sess, acc)
                selected = select_files(filelist, args.max_file_mb, args.file_limit_per_accession)
                selected.to_csv(acc_dir / "selected_files.csv", index=False)
                if selected.empty:
                    records.append(
                        {
                            "accession": acc,
                            "file": "",
                            "status": "filelist_error",
                            "size_mb": "",
                            "selection_reason": "",
                            "url": filelist_url,
                            "note": f"{exc}; directory fallback produced no selected files",
                        }
                    )
                    continue
            except Exception as fallback_exc:
                records.append(
                    {
                        "accession": acc,
                        "file": "",
                        "status": "filelist_error",
                        "size_mb": "",
                        "selection_reason": "",
                        "url": filelist_url,
                        "note": f"{exc}; directory fallback failed: {fallback_exc}",
                    }
                )
                continue
        ok_to_download, evidence_note = benchmark_evidence_reason(selected)
        if not ok_to_download:
            records.append(
                {
                    "accession": acc,
                    "file": "",
                    "status": "not_benchmark_ready_filelist",
                    "size_mb": "",
                    "selection_reason": "",
                    "url": filelist_url,
                    "note": evidence_note,
                }
            )
            continue

        acc_manifest = {
            "accession": acc,
            "filelist_url": filelist_url,
            "selected_files": [],
        }
        base = suppl_base_url(acc)
        for selected_row in selected.itertuples(index=False):
            name = str(getattr(selected_row, "Name"))
            size_bytes = int(getattr(selected_row, "size_bytes", 0) or 0)
            reason = str(getattr(selected_row, "selection_reason", ""))
            is_selected = bool(getattr(selected_row, "selected", False))
            url_override = str(getattr(selected_row, "url_override", "") or "")
            urls = [url_override] if url_override.startswith("http") else candidate_urls(acc, name)
            url = urls[0]
            dest = acc_dir / "raw" / name
            status = "selected_no_download"
            note = ""
            decompressed = ""
            if not is_selected:
                status = "skipped"
            elif args.download:
                if total_downloaded + size_bytes > args.max_total_mb * 1024 * 1024:
                    status = "skipped_total_cap"
                else:
                    try:
                        status, written, used_url, download_note = download_one(sess, urls, dest)
                        total_downloaded += int(written)
                        if used_url:
                            url = used_url
                        if download_note:
                            note = download_note
                        if args.decompress_h5ad:
                            decompressed = maybe_decompress_h5ad(dest)
                    except Exception as exc:
                        status = "download_error"
                        note = str(exc)
            records.append(
                {
                    "accession": acc,
                    "file": name,
                    "status": status,
                    "size_mb": round(size_bytes / 1024 / 1024, 3),
                    "selection_reason": reason,
                    "url": url,
                    "local_path": str(dest if dest.exists() else ""),
                    "decompressed_h5ad": decompressed,
                    "note": note,
                }
            )
            acc_manifest["selected_files"].append(records[-1])
        manifest["accessions"].append(acc_manifest)
        time.sleep(args.sleep)

    report = pd.DataFrame(records)
    report_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    if report_path.exists() and not report.empty and report_path.stat().st_size > 2:
        try:
            previous = pd.read_csv(report_path)
            report = pd.concat([previous, report], ignore_index=True)
            report = report.drop_duplicates(["accession", "file", "status"], keep="last")
        except pd.errors.EmptyDataError:
            pass
    report.to_csv(report_path, index=False)
    manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(f"wrote {report_path}")
    print(f"total_downloaded_mb={total_downloaded / 1024 / 1024:.2f}")
    if report.empty:
        print("no records")
    else:
        print(report.tail(30).to_string(index=False, max_colwidth=100))


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        sys.exit(130)
